"""Exportiert den gemeinsamen Testkorpus als JSON fuer Implementierungen.

Quellen sind die Listen in scripts/xtjson_ref.py (in main()) und in
scripts/tests_*.py. Das Ergebnis lesen die Tests der Implementierungen,
zum Beispiel xtjson-js/test/corpus.test.js.

Aufruf:
  python3 scripts/export_corpus.py [Datei]           schreibt die Datei
  python3 scripts/export_corpus.py --check [Datei]   prueft, ob die Datei aktuell ist

Standard fuer Datei: xtjson-js/test/corpus.json

Von den abgelehnten Definitionen (BAD_DEFS) werden nur die exportiert, die
sich als JSON darstellen lassen (c_bad_values); Werte wie NaN, Mengen oder
beliebige Objekte prueft jede Implementierung selbst.
"""
import ast
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = ROOT / 'xtjson-js' / 'test' / 'corpus.json'

sys.path.insert(0, str(ROOT / 'scripts'))
sys.dont_write_bytecode = True

import tests_definitionen as tc  # noqa: E402
import tests_mehrzeilige_strings as tb  # noqa: E402
import tests_zeilenumbruch_strings as ta  # noqa: E402


def ref_lists():
    """Die Listen invalid, valid und samples aus xtjson_ref.main()."""
    src = (ROOT / 'scripts' / 'xtjson_ref.py').read_text(encoding='utf-8')
    main = next(n for n in ast.parse(src).body
                if isinstance(n, ast.FunctionDef) and n.name == 'main')
    lists = {}
    for node in ast.walk(main):
        if (isinstance(node, ast.Assign) and len(node.targets) == 1
                and isinstance(node.targets[0], ast.Name)
                and node.targets[0].id in ('invalid', 'valid', 'samples')):
            expr = compile(ast.Expression(node.value), 'xtjson_ref.py', 'eval')
            lists[node.targets[0].id] = eval(expr, {'json': json, '__builtins__': {}})
    missing = {'invalid', 'valid', 'samples'} - set(lists)
    if missing:
        raise SystemExit('FEHLER: Listen in xtjson_ref.main() nicht gefunden: %s' % ', '.join(sorted(missing)))
    return lists


def defs_label(defs):
    """'D' fuer die Definitionen D, sonst None oder nur die benannten Werte."""
    if defs is tc.D:
        return 'D'
    if not defs:
        return None
    if set(defs) != {'values'}:
        raise SystemExit('FEHLER: unbekannte Definitionen: %r' % (defs,))
    return {'values': defs['values']}


def bad_values():
    """Die abgelehnten benannten Werte aus BAD_DEFS, die sich als JSON darstellen lassen."""
    out = []
    for defs in tc.BAD_DEFS:
        if set(defs) != {'values'}:
            raise SystemExit('FEHLER: unbekannte Definitionen: %r' % (defs,))
        try:
            json.dumps(defs['values'], allow_nan=False)
        except (TypeError, ValueError):
            continue
        out.append(defs['values'])
    return out


def corpus():
    ref = ref_lists()
    return {
        'source': 'generated by scripts/export_corpus.py from scripts/xtjson_ref.py and scripts/tests_*.py; do not edit',
        'ref_valid': [[t, v] for t, v in ref['valid']],
        'ref_invalid': ref['invalid'],
        'ref_json_samples': ref['samples'],
        'a_valid': [[t, v] for t, v in ta.VALID],
        'a_invalid': ta.INVALID,
        'b_valid': [[t, v] for t, v in tb.VALID],
        'b_invalid': tb.INVALID,
        'c_values': tc.VALUES,
        'c_valid': [[t, defs_label(d), v] for t, d, v in tc.VALID],
        'c_invalid': [[t, defs_label(d)] for t, d in tc.INVALID],
        'c_bad_values': bad_values(),
    }


def render():
    # ensure_ascii: Sonderzeichen wie U+2028 bleiben als Escape-Sequenz sichtbar.
    return json.dumps(corpus(), ensure_ascii=True, indent=1, allow_nan=False) + '\n'


def main(argv):
    check = '--check' in argv
    args = [a for a in argv if a != '--check']
    out = Path(args[0]) if args else DEFAULT_OUT
    text = render()
    if check:
        current = out.read_text(encoding='utf-8') if out.exists() else None
        if current != text:
            print('FEHLER: %s ist nicht aktuell; scripts/export_corpus.py ausfuehren' % out)
            return 1
        print('ERGEBNIS: OK, %s ist aktuell' % out)
        return 0
    out.write_text(text, encoding='utf-8', newline='\n')
    print('ERGEBNIS: OK, %s geschrieben' % out)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
